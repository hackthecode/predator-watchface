# Generates res/raw/watchface.xml for the Predator face.
# Layers, back to front: housing / lit numerals / start-up scramble / readouts / gauges / ranging mark / glass /
# thermal view (revealed for 4 s by a tap) / always-on.
$root = Split-Path $PSScriptRoot -Parent
function Esc($s) { [System.Security.SecurityElement]::Escape($s) }

$H = '([IS_24_HOUR_MODE] ? [HOUR_0_23] : [HOUR_1_12])'
$cells = @(
  @{ x = 66;  expr = "floor($H / 10)" },
  @{ x = 148; expr = "($H % 10)" },
  @{ x = 250; expr = "floor([MINUTE] / 10)" },
  @{ x = 332; expr = "([MINUTE] % 10)" }
)
$CY = 146; $CW = 70; $CH = 128; $PAD = 14        # keep in sync with PredatorRender
$HR = 'round([HEART_RATE])'
$STEPPCT = 'clamp([STEP_COUNT] * 100 / clamp([STEP_GOAL], 1, 100000), 1, 100)'
$RED = "#ffff3c2d"; $DIM = "#ff8c1a12"; $WHITE = "#ffffffff"

function Glyphs($pre, $pad, $ind) {
  $sb = ""
  foreach ($c in $cells) { for ($k = 0; $k -le 9; $k++) {
    $sb += "$ind<PartImage x=`"$($c.x - $pad)`" y=`"$($CY - $pad)`" width=`"$($CW + 2 * $pad)`" height=`"$($CH + 2 * $pad)`" alpha=`"0`"><Transform target=`"alpha`" value=`"$(Esc "($($c.expr) == $k) ? 255 : 0")`"/><Image resource=`"$pre$k`"/></PartImage>`n" } }
  $sb
}
function Txt($x, $y, $w, $h, $size, $color, $body, $alphaExpr = $null, $alpha0 = 255) {
  $a = if ($alphaExpr) { " alpha=`"$alpha0`"" } else { "" }
  $t = if ($alphaExpr) { "<Transform target=`"alpha`" value=`"$(Esc $alphaExpr)`"/>" } else { "" }
  "<PartText x=`"$x`" y=`"$y`" width=`"$w`" height=`"$h`"$a>$t<Text align=`"CENTER`"><Font family=`"mono_bold`" size=`"$size`" color=`"$color`">$body</Font></Text></PartText>`n"
}
function Tpl($tpl, [string[]]$exprs) { "<Template>$(Esc $tpl)" + (($exprs | ForEach-Object { "<Parameter expression=`"$(Esc $_)`"/>" }) -join "") + "</Template>" }
# the readable time under the numerals, the date, and the pulse; $c = text colour
function Readouts($c, $ind) {
  $s  = $ind + (Txt 163 84 140 24 19 $c ("<Upper>" + (Tpl "%s %s %s" @("[DAY_OF_WEEK_S]", "[DAY]", "[MONTH_S]")) + "</Upper>"))
  $s += $ind + (Txt 163 292 140 26 20 $c (Tpl "%s:%s" @("[HOUR_0_23_Z]", "[MINUTE_Z]")) "[IS_24_HOUR_MODE] ? 255 : 0" 255)
  $s += $ind + (Txt 163 292 140 26 20 $c (Tpl "%s:%s" @("[HOUR_1_12_Z]", "[MINUTE_Z]")) "[IS_24_HOUR_MODE] ? 0 : 255" 0)
  $s += $ind + (Txt 190 386 86 26 20 $c (Tpl "%s" @($HR)) "($HR > 0) ? 255 : 0" 0)
  $s += $ind + (Txt 190 386 86 26 20 $c "--" "($HR > 0) ? 0 : 255" 255)
  $s
}
function Bar($name, $x, $widthExpr) {
  @"
      <Group name="$name" x="$x" y="352" width="110" height="12">
        <PartDraw x="0" y="0" width="110" height="12" renderMode="MASK">
          <Rectangle x="0" y="0" width="110" height="12"><Transform target="width" value="$(Esc $widthExpr)"/><Fill color="#ffffffff"/></Rectangle>
        </PartDraw>
        <PartImage x="0" y="0" width="110" height="12" renderMode="SOURCE"><Image resource="pr_bar"/></PartImage>
      </Group>

"@
}
function Frames($list, $ind) { ($list | ForEach-Object { "$ind<Image resource=`"$_`"/>`n" }) -join "" }
$U = 'clamp([ACCELEROMETER_ANGLE_X] / 30, -1, 1)'
$V = 'clamp([ACCELEROMETER_ANGLE_Y] / 40, -1, 1)'

$xml = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- PREDATOR: an alien hunter's wrist computer, Watch Face Format v2, 466x466. Generated by tools/gen-xml.ps1 - edit that, not this. -->
<WatchFace width="466" height="466">
  <Metadata key="CLOCK_TYPE" value="DIGITAL"/>
  <Metadata key="PREVIEW_TIME" value="18:42:00"/>
  <Scene backgroundColor="#ff000000">

    <PartImage name="bg" x="0" y="0" width="466" height="466" alpha="255">
      <Variant mode="AMBIENT" target="alpha" value="0"/>
      <Image resource="pr_bg"/>
    </PartImage>

    <!-- the time in the hunter's numerals: bars count 1-4, the spine is 5, the diamond is 0 -->
    <Group name="glyphs" x="0" y="0" width="466" height="466" alpha="255">
      <Variant mode="AMBIENT" target="alpha" value="0"/>
$(Glyphs "pr_g" $PAD "      ")    </Group>

    <!-- start-up: the cells flick through random numerals for half a second each time the face becomes visible -->
    <PartAnimatedImage name="scramble" x="38" y="122" width="390" height="212">
      <Variant mode="AMBIENT" target="alpha" value="0"/>
      <AnimationController play="ON_VISIBLE" loopCount="1" beforePlaying="FIRST_FRAME" afterPlaying="HIDE"/>
      <SequenceImages loopCount="1" frameRate="16" thumbnail="pr_off">
$(Frames (0..7 | ForEach-Object { "pr_s$_" }) "        ")      </SequenceImages>
    </PartAnimatedImage>

    <Group name="readouts" x="0" y="0" width="466" height="466" alpha="255">
      <Variant mode="AMBIENT" target="alpha" value="0"/>
$(Readouts $RED "      ")    </Group>

    <!-- gauges: power (battery) and track (steps toward the daily goal) -->
    <Group name="gauges" x="0" y="0" width="466" height="466" alpha="255">
      <Variant mode="AMBIENT" target="alpha" value="0"/>
$(Bar "pwr" 108 "1.1 * clamp([BATTERY_PERCENT], 1, 100)")$(Bar "trk" 248 "1.1 * $STEPPCT")    </Group>

    <!-- three-dot ranging mark, wandering over the display with the tilt of the wrist -->
    <PartImage name="tri" x="191" y="170" width="84" height="78" alpha="255">
      <Variant mode="AMBIENT" target="alpha" value="0"/>
      <Transform target="x" value="$(Esc "191 + 120 * $U")"/>
      <Transform target="y" value="$(Esc "170 + 45 * $V")"/>
      <Image resource="pr_tri"/>
    </PartImage>

    <PartImage name="glass" x="0" y="0" width="466" height="466" alpha="255">
      <Variant mode="AMBIENT" target="alpha" value="0"/>
      <Transform target="x" value="$(Esc "8 * $U")"/>
      <Image resource="pr_hl"/>
    </PartImage>

    <!-- thermal view: a tap switches the whole face to heat vision for four seconds -->
    <Group name="thermal" x="0" y="0" width="466" height="466" alpha="255">
      <Variant mode="AMBIENT" target="alpha" value="0"/>
      <PartAnimatedImage x="0" y="0" width="466" height="466" renderMode="MASK">
        <AnimationController play="TAP" loopCount="1" beforePlaying="FIRST_FRAME" afterPlaying="FIRST_FRAME"/>
        <SequenceImages loopCount="1" frameRate="10" thumbnail="pr_off">
$(Frames (@("pr_off") + (1..40 | ForEach-Object { "pr_on" }) + @("pr_off")) "          ")        </SequenceImages>
      </PartAnimatedImage>
      <Group x="0" y="0" width="466" height="466" renderMode="SOURCE">
        <PartImage x="0" y="0" width="466" height="466"><Image resource="pr_thermal"/></PartImage>
$(Glyphs "pr_t" $PAD "        ")$(Readouts $WHITE "        ")        $(Txt 104 349 118 18 15 $WHITE (Tpl "PWR %s%%" @("[BATTERY_PERCENT]")))        $(Txt 244 349 118 18 15 $WHITE (Tpl "TRK %s" @("[STEP_COUNT]")))      </Group>
    </Group>

    <!-- always-on: thin dim numerals and the readable time, nothing else -->
    <Group name="ambient" x="0" y="0" width="466" height="466" alpha="0">
      <Variant mode="AMBIENT" target="alpha" value="200"/>
$(Glyphs "pr_a" 0 "      ")      $(Txt 163 292 140 26 20 $DIM (Tpl "%s:%s" @("[HOUR_0_23_Z]", "[MINUTE_Z]")) "[IS_24_HOUR_MODE] ? 255 : 0" 255)      $(Txt 163 292 140 26 20 $DIM (Tpl "%s:%s" @("[HOUR_1_12_Z]", "[MINUTE_Z]")) "[IS_24_HOUR_MODE] ? 0 : 255" 0)    </Group>

  </Scene>
</WatchFace>
"@
Set-Content (Join-Path $root "res\raw\watchface.xml") $xml -NoNewline -Encoding utf8NoBOM
Write-Host "watchface.xml written"
